#!/usr/bin/env python3
"""Build a larger, fully synthetic posting corpus for offline demos and trace recording.

    python tools/build_demo_corpus.py [out.json]     # default: demo/corpus/corpus.json

The 120 postings are generated by pure index arithmetic: no random module, no network, no
clock. Every company, city, title, description and URL is invented here. The only fields
taken from samples/ are the board name (source) and the sample file each posting is
attributed to (derived_from); no captured text is copied into a posting.

Reach-gate mix, by construction: posting n (1-based) is in_reach when (n-1) % 3 == 0,
stretch when == 1, out_of_reach when == 2, so each class holds exactly 40 postings.
Two runs produce byte-identical output.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SAMPLES = ROOT / "samples"
DEFAULT_OUT = ROOT / "demo" / "corpus" / "corpus.json"

POSTING_COUNT = 120

# Captured payload file -> the board it came from. smartrecruiters_detail.json is the
# second record for the smartrecruiters board, so it maps to that board too.
SAMPLE_BOARD = {
    "greenhouse.json": "greenhouse",
    "lever.json": "lever",
    "ashby.json": "ashby",
    "workable.json": "workable",
    "smartrecruiters.json": "smartrecruiters",
    "smartrecruiters_detail.json": "smartrecruiters",
    "remotive.json": "remotive",
    "remoteok.json": "remoteok",
    "arbeitnow.json": "arbeitnow",
}
SAMPLE_ORDER = tuple(SAMPLE_BOARD)  # 9 payloads, fixed order

SOURCES = ("greenhouse", "lever", "ashby", "workable", "smartrecruiters",
           "remotive", "remoteok", "arbeitnow")

COMPANIES = (
    "Northwind Analytics", "Meridian Labs", "Harbor Point Systems", "Quillfeather Software",
    "Tallgrass Data Co", "Brightwater Logic", "Ironleaf Security", "Cedarline Robotics",
    "Foxglove Works", "Ostrava Peak Cloud",
)

LOCATIONS = (
    "Winnipeg", "Toronto", "Vancouver", "Montreal", "Ottawa", "Edmonton", "Halifax",
    "Victoria", "Kitchener", "Markham", "Burnaby", "Surrey", "Mississauga", "Quebec City",
    "Remote (Canada)", "Hybrid",
)

DOMAINS = (
    "payments reconciliation", "endpoint security", "log analytics", "customer data platforms",
    "logistics routing", "clinical scheduling", "education tooling", "developer productivity",
    "warehouse inventory", "field service dispatch",
)

STACKS = ("Python services", "SQL databases", "cloud pipelines", "test automation",
          "REST APIs", "event streaming")

# Reach-gate classes, in order of (n-1) % 3. Each entry is (title, years phrase or None).
# in_reach: intern/junior/entry/plain-mid titles, no years asked or 1-2 years.
# stretch:  senior title, or a plain title asking 3-4 years.
# out:      staff/principal/lead/manager/director/architect title, or a plain title asking 5+.
CLASS_TITLES = {
    "in_reach": (
        ("Junior Security Analyst", None),
        ("Software Engineering Intern", None),
        ("Entry-Level Data Analyst", "1+ years of experience"),
        ("Python Developer", "2 years of experience"),
    ),
    "stretch": (
        ("Senior Python Developer", None),
        ("Sr. Data Engineer", "1+ years of experience"),
        ("Support Engineer", "3-4 years of experience"),
        ("Security Analyst", "3+ years of experience"),
    ),
    "out_of_reach": (
        ("Staff Software Engineer", None),
        ("Engineering Manager", None),
        ("Principal Data Engineer", None),
        ("Software Developer", "6+ years of experience"),
    ),
}
CLASS_ORDER = ("in_reach", "stretch", "out_of_reach")


def _posting(n: int) -> dict:
    i = n - 1
    cls = CLASS_ORDER[i % 3]
    variant = (i // 3) % 4
    title, years_phrase = CLASS_TITLES[cls][variant]
    source = SOURCES[i % len(SOURCES)]
    sample = SAMPLE_ORDER[i % len(SAMPLE_ORDER)]
    company = COMPANIES[i % len(COMPANIES)]
    location = LOCATIONS[i % len(LOCATIONS)]
    domain = DOMAINS[i % len(DOMAINS)]
    stack = STACKS[(i // 2) % len(STACKS)]

    sentences = [
        f"The team builds internal tooling for {domain}.",
        f"You will write and review {stack}, ship tests with each change, and document how the system runs.",
    ]
    if years_phrase:
        sentences.append(f"We ask for {years_phrase} with {stack.lower()}.")
    elif cls == "in_reach":
        sentences.append("Prior internship or project work is welcome but not required.")
    else:
        sentences.append("The role is open to candidates who can explain their past projects clearly.")
    if i % 2 == 0:
        sentences.append("Benefits include a flexible schedule and a training budget.")

    return {
        "uid": f"{source}:corpus:{n:04d}",
        "source": source,
        "company": company,
        "title": title,
        "location": location,
        "url": f"https://example.invalid/corpus/{n:04d}",
        "description": " ".join(sentences),
        "posted_at": f"2026-10-{(i % 28) + 1:02d}T00:00:00+00:00",
        "remote": location.startswith("Remote"),
        "derived_from": sample,
    }


def _check_samples() -> None:
    for name in SAMPLE_ORDER:
        path = SAMPLES / name
        if not path.is_file():
            raise SystemExit(f"missing captured payload: samples/{name}")
        json.loads(path.read_text(encoding="utf-8"))  # must parse; content is not copied


def build() -> dict:
    _check_samples()
    postings = [_posting(n) for n in range(1, POSTING_COUNT + 1)]
    return {
        "note": ("Synthetic demo corpus. Every company, location, title, description and URL "
                 "is invented; no posting is real and no board URL is live. Only the source "
                 "board and derived_from sample name come from samples/."),
        "generated_by": "tools/build_demo_corpus.py",
        "posting_count": len(postings),
        "postings": postings,
    }


def write(out_path: Path) -> dict:
    data = build()
    text = json.dumps(data, indent=2, sort_keys=True, ensure_ascii=True) + "\n"
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_bytes(text.encode("ascii"))
    return data


def main(argv: list[str]) -> int:
    out = Path(argv[1]) if len(argv) > 1 else DEFAULT_OUT
    data = write(out)
    print(f"{out.name}: {data['posting_count']} postings")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
